"""Generate annex_c.rs: the CxtVLC code tables of ITU-T T.814 (06/2019) Annex C.

Input is the text of the Recommendation's PDF, as extracted with
`pdftotext -layout T-REC-T.814-201906-I!!PDF-E.pdf t814.txt` (the PDF is free from
https://www.itu.int/rec/T-REC-T.814). The two tables appear there as C-style initialisers,
`CxtVLC_table_0 = {{c_q, rho_q, u_off, eps_k, eps_1, w, l_w}, ...}`; this script copies their
entries unchanged into Rust arrays and checks that each context's code is prefix-free, complete
(Kraft sum 1) and at most 7 bits long, so that every 7-bit lookahead matches exactly one
codeword, which the decoder's lookup tables rely on.

Usage: python3 gen_annex_c.py t814.txt > annex_c.rs
"""

import re
import sys


def parse(text: str, name: str) -> list[tuple[int, ...]]:
    start = text.index(name + " = {{")
    end = text.index("}}", start) + 2
    body = text[start:end]
    entries = re.findall(r"\{([^{}]*)\}", body)
    return [tuple(int(f, 0) for f in e.split(",")) for e in entries]


def check(table: list[tuple[int, ...]], name: str) -> None:
    for cxt in range(8):
        codes = [(w, l) for (c, _rho, _u, _ek, _e1, w, l) in table if c == cxt]
        for w, l in codes:
            assert 1 <= l <= 7 and w < (1 << l), (name, cxt, w, l)
        for i, (w1, l1) in enumerate(codes):
            for w2, l2 in codes[i + 1 :]:
                n = min(l1, l2)
                assert (w1 ^ w2) & ((1 << n) - 1), f"{name}: context {cxt} not prefix-free"
        assert sum(1 << (7 - l) for _, l in codes) == 128, f"{name}: context {cxt} not complete"


def main() -> None:
    text = open(sys.argv[1], encoding="utf-8").read()
    out = [
        "// Generated by gen_annex_c.py from the text of ITU-T T.814 (06/2019) Annex C; do not edit.",
        "// Fields: (c_q, rho_q, u_off, eps_k, eps_1, codeword w (first bit in the LSB), length l_w).",
        "",
    ]
    for i in range(2):
        name = f"CxtVLC_table_{i}"
        table = parse(text, name)
        check(table, name)
        out.append(f"/// `{name}`: {len(table)} codewords for quads in the {'initial' if i == 0 else 'non-initial'} line-pair.")
        out.append(f"pub(super) const CXT_VLC_TABLE_{i}: [[u8; 7]; {len(table)}] = [")
        for e in table:
            out.append("    [" + ", ".join(f"0x{v:02X}" if k in (1, 3, 4, 5) else str(v) for k, v in enumerate(e)) + "],")
        out.append("];")
        out.append("")
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
