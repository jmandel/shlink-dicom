"""Generate src/dict.rs, the tag -> VR table used to rewrite Implicit VR data sets as Explicit VR.

Source: the DICOM standard's PS3.6 DocBook XML (tables 6-1 and 7-1), for example
    curl -sSLO https://dicom.nema.org/medical/dicom/current/source/docbook/part06/part06.xml
    python3 tools/gen_dict.py part06.xml > src/dict.rs
Retired elements are kept: old files still carry them. Tags with x digits (repeating groups such as
60xx or 50xx) go to a masked list. Elements listed with several VRs keep them all; the transcoder
picks one from the data set (dict.rs `Vr`).
"""
import re
import sys
import xml.etree.ElementTree as ET

D = "{http://docbook.org/ns/docbook}"


def text(e):
    return "".join(e.itertext()).replace("\u200b", "").strip()


def main(path):
    root = ET.parse(path).getroot()
    edition = next(text(s) for s in root.iter(D + "subtitle"))
    exact, masked = {}, {}
    for tb in root.iter(D + "table"):
        if tb.get("{http://www.w3.org/XML/1998/namespace}id") not in ("table_6-1", "table_7-1"):
            continue
        for tr in tb.iter(D + "tr"):
            tds = tr.findall(D + "td")
            if len(tds) < 4:
                continue
            tag, vr = text(tds[0]), text(tds[3])
            m = re.fullmatch(r"\(([0-9A-Fx]{4}),([0-9A-Fx]{4})\)", tag)
            if not m or not vr or "See Note" in vr:
                continue
            vrs = tuple(v.strip() for v in vr.split(" or "))
            if not all(re.fullmatch(r"[A-Z]{2}", v) for v in vrs):
                continue
            hexs = m.group(1) + m.group(2)
            if "x" in hexs:
                mask = int("".join("0" if c == "x" else "F" for c in hexs), 16)
                value = int(hexs.replace("x", "0"), 16)
                masked[(mask, value)] = vrs
            else:
                exact[int(hexs, 16)] = vrs
    print(f"//! Tag -> VR for the standard data elements, generated by tools/gen_dict.py from {edition}")
    print("//! (tables 6-1 and 7-1; retired elements included). Do not edit by hand.")
    print("// Several VRs: the transcoder chooses (see `crate::dict_vr`).")
    print("#[rustfmt::skip]")
    print(f"pub(crate) static EXACT: [(u32, &[[u8; 2]]); {len(exact)}] = [")
    for t in sorted(exact):
        print(f"    (0x{t:08X}, &[{', '.join('*b%r' % v for v in exact[t])}]),".replace("*b'", '*b"').replace("'", '"'))
    print("];")
    print("/// (mask, value, VRs) for tags with x digits, most specific mask first.")
    print("#[rustfmt::skip]")
    print(f"pub(crate) static MASKED: [(u32, u32, &[[u8; 2]]); {len(masked)}] = [")
    for (mask, value) in sorted(masked, key=lambda k: (-bin(k[0]).count("1"), k[1])):
        vrs = masked[(mask, value)]
        print(f"    (0x{mask:08X}, 0x{value:08X}, &[{', '.join('*b%r' % v for v in vrs)}]),".replace("*b'", '*b"').replace("'", '"'))
    print("];")


main(sys.argv[1])
